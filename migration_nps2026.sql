-- National Pay Scale 2026 — চাকরি (বেতন ও ভাতাদি) আদেশ, ২০২৬
-- S.R.O. 347-Law/2026, Bangladesh Gazette 17 September 2026, effective 1 July 2026.
--
-- Run this in the Supabase SQL editor before using Payroll Admin →
-- Grades → Pay Fixation. It does three things:
--   1. gives the pay matrix a scale dimension, so the 2015 and 2026
--      ladders live side by side and old payslips still reproduce;
--   2. seeds the 2026 ladders exactly as the gazette prints them;
--   3. adds payroll.pay_fixations — one auditable row per person per
--      conversion, which is what the বেতন নির্ধারণী বিবরণী prints from.

create table if not exists payroll.pay_scales (
  id             bigint generated always as identity primary key,
  code           text not null unique,
  name           text not null,
  effective_from date not null,
  is_active      boolean not null default true,
  created_at     timestamptz not null default now()
);

insert into payroll.pay_scales (code, name, effective_from) values
  ('NPS-2015', 'National Pay Scale 2015', '2015-07-01'),
  ('NPS-2026', 'National Pay Scale 2026', '2026-07-01')
on conflict (code) do nothing;

-- Every existing cell belongs to the 2015 scale.
alter table payroll.grade_step_values add column if not exists scale_id bigint;
update payroll.grade_step_values
   set scale_id = (select id from payroll.pay_scales where code = 'NPS-2015')
 where scale_id is null;
alter table payroll.grade_step_values alter column scale_id set not null;

-- The key has to widen: the same grade+step now exists once per scale.
do $$
declare pk text;
begin
  select conname into pk from pg_constraint
   where conrelid = 'payroll.grade_step_values'::regclass and contype = 'p';
  if pk is not null then
    execute format('alter table payroll.grade_step_values drop constraint %I', pk);
  end if;
end $$;
create unique index if not exists grade_step_values_scale_key
  on payroll.grade_step_values (scale_id, grade_id, step_id);

