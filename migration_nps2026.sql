-- One row per person per conversion: what they were on, what the order
-- fixes them at, and what is actually payable in the phased months.
create table if not exists payroll.pay_fixations (
  id                bigint generated always as identity primary key,
  user_id           text not null,
  effective_date    date not null,
  from_scale_id     bigint,
  to_scale_id       bigint,
  grade_id          bigint,
  to_grade_id       bigint,
  from_step_id      bigint,
  to_step_id        bigint,
  current_basic     numeric,
  diff              numeric,
  computed_basic    numeric,
  increment_applied boolean not null default false,
  fixed_basic       numeric,
  phase_percent     numeric,
  payable_basic     numeric,
  month             integer,
  year              integer,
  higher_grade      boolean not null default false,
  note              text,
  created_by        text,
  created_at        timestamptz not null default now(),
  unique (user_id, effective_date, to_scale_id)
);
create index if not exists pay_fixations_user_idx on payroll.pay_fixations (user_id);
